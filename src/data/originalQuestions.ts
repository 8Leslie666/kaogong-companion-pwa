import type { AnswerKey, ExamModule, ObjectiveQuestion } from '../domain/types'

const PACK_ID = 'original-core-v1'
const SOURCE_URL = 'https://www.forestry.gov.cn/c/www/gsgg/645383.jhtml'
const keys: AnswerKey[] = ['A', 'B', 'C', 'D']

type ConceptSeed = [stem: string, answer: string, distractors: [string, string, string], explanation: string, submodule: string]

function conceptQuestions(module: ExamModule, prefix: string, seeds: ConceptSeed[]): ObjectiveQuestion[] {
  return seeds.map(([stem, answer, distractors, explanation, submodule], index) => {
    const answerIndex = index % 4
    const values = [...distractors]
    values.splice(answerIndex, 0, answer)
    return {
      id: `${prefix}-${String(index + 1).padStart(3, '0')}`,
      packId: PACK_ID,
      module,
      submodule,
      stem,
      options: Object.fromEntries(keys.map((key, optionIndex) => [key, values[optionIndex]])) as Record<AnswerKey, string>,
      answer: keys[answerIndex],
      explanation,
      difficulty: ((index % 3) + 2) as 2 | 3 | 4,
      source: '考公陪跑宝典原创题',
      sourceUrl: SOURCE_URL,
      license: '原创内容，仅供学习使用',
      year: 2026,
      region: '全国',
      tags: [module, submodule, '原创'],
    }
  })
}

